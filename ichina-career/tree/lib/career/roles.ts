export type FieldFilter = "all" | "today" | "institutions" | "capital" | "cvc" | "stretch";

export function inField(role: CareerRole, filter: FieldFilter, now = new Date()): boolean {
  if (role.status === "skip") return false;
  if (filter === "all") return true;
  if (filter === "today") {
    return role.bands.includes("today") && isOpen(role.closeAt, now);
  }
  return role.bands.includes(filter);
}

export function sortField(list: CareerRole[], now = new Date()): CareerRole[] {
  return [...list].sort((a, b) => {
    const ua = urgency(a.closeAt, now);
    const ub = urgency(b.closeAt, now);
    const order = { now: 0, soon: 1, week: 2, open: 3 };
    if (order[ua] !== order[ub]) return order[ua] - order[ub];
    if (a.tier === "ideal" && b.tier !== "ideal") return -1;
    if (b.tier === "ideal" && a.tier !== "ideal") return 1;
    const am = a.closeAt ? msUntil(a.closeAt, now) : Number.POSITIVE_INFINITY;
    const bm = b.closeAt ? msUntil(b.closeAt, now) : Number.POSITIVE_INFINITY;
    if (am !== bm) return am - bm;
    return a.rank - b.rank;
  });
}

export function nextMoves(now = new Date()): CareerRole[] {
  const open = roles.filter((r) => r.status === "live" && isOpen(r.closeAt, now));
  const today = sortField(
    open.filter((r) => r.bands.includes("today") || r.tier === "ideal"),
    now,
  );
  const rest = sortField(
    open.filter((r) => !today.includes(r)),
    now,
  );
  return [...today, ...rest].slice(0, 8);
}
